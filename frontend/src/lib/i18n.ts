export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const e = dict[key];
  let s = e ? (lang === 'fr' ? e[1] : e[0]) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Reactive helper: subscribes the component to language changes */
export function useT() {
  const language = useUiStore(s => s.language);
  const t = (key: string, vars?: Record<string, string | number>) => translate(language, key, vars);
  return { t, language };
}

/** Non-reactive translate for module-level render helpers (they re-run whenever
 * the owning component re-renders, which is reactive enough since components
 * subscribe via useT). */
export const tNow = (key: string, vars?: Record<string, string | number>) =>
  translate(useUiStore.getState().language, key, vars);
